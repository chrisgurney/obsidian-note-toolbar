import { spawn } from 'child_process';
import chokidar from "chokidar";
import esbuild, { analyzeMetafile } from "esbuild";
import fs from 'fs';
import { builtinModules } from 'node:module';
import process from "process";
import { fileInliner } from "./build/file-inliner.mjs";

// build cache
const CACHE_DIR = 'node_modules/.cache';
fs.mkdirSync(CACHE_DIR, { recursive: true });

/* ****************************************************************************
 * BUILD FLAGS
 * ************************************************************************** */

const ESBUILD_BANNER =
`/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const isBuildAnalyzeMode = (process.argv[2] === "analyze");
const isBuildProdMode = (process.argv[2] === "production");

/* ****************************************************************************
 * PLUGINS
 * ************************************************************************** */

const docsPlugin = {
	name: 'docs',
	setup(build) {
		build.onStart(async () => {
			await new Promise((resolve, reject) => {
				const docs = spawn(process.execPath, ['build/docs.mjs'], { stdio: 'inherit' });
				docs.on('close', (code) => {
					if (code === 0) resolve();
					else reject(new Error(`docs build failed with code ${code}`));
				});
				docs.on('error', (error) => reject(new Error(`docs build failed to start: ${error.message}`)));
			});
		});
	},
};

const typecheckPlugin = {
	name: 'typecheck',
	setup(build) {
		build.onEnd(async () => {
			return new Promise((resolve) => {
				console.log('[typecheck] running...');
				const tsc = spawn('tsc', [
					'--noEmit',
					'--skipLibCheck',
					'--incremental',
					'--tsBuildInfoFile', `${CACHE_DIR}/tsconfig.tsbuildinfo`
				], {
					stdio: 'inherit' // pipes stdout/stderr directly, preserving colors
				});
				tsc.on('close', (code) => {
					if (code === 0) {
						console.log('\x1b[32m[typecheck] ✓ passed\x1b[0m');
					} else {
						console.log('\x1b[31m[typecheck] ✗ failed\x1b[0m');
					}
					resolve();
				});
			});
		});
	},
};

const eslintPlugin = {
	name: 'eslint',
	setup(build) {
		build.onEnd(async () => {
			return new Promise((resolve) => {
				console.log('[eslint] running...');
				const eslint = spawn('npx', [
					'eslint', '.', '--ext', '.ts',
					'--cache', '--cache-location', `${CACHE_DIR}/.eslintcache`
				], {
					stdio: 'inherit',
					shell: process.platform === 'win32' // needed for Windows
				});
				eslint.on('close', (code) => {
					if (code === 0) {
						console.log('\x1b[32m[eslint] ✓ passed\x1b[0m');
					} else {
						console.log('\x1b[33m[eslint] ⚠ warnings/errors found\x1b[0m');
					}
					resolve();
				});
			});
		});
	},
};

const stylelintPlugin = {
	name: 'stylelint',
	setup(build) {
		build.onEnd(async () => {
			return new Promise((resolve) => {
				console.log('[stylelint] running...');
				const stylelint = spawn('npx', [
					'stylelint', '**/*.css',
					'--cache', '--cache-location', `${CACHE_DIR}/.stylelintcache`
				], {
					stdio: 'inherit',
					shell: process.platform === 'win32', // needed for Windows
					env: {
						...process.env,
						NODE_OPTIONS: '--no-warnings'
					}
				});
				stylelint.on('close', (code) => {
					if (code === 0) {
						console.log('\x1b[32m[stylelint] ✓ passed\x1b[0m');
					} else {
						console.log('\x1b[33m[stylelint] ⚠ warnings/errors found\x1b[0m');
					}
					resolve();
				});
			});
		});
	},
};

// intermediate file, so the published styles.css can differ from the inlined source
const STYLES_INLINED = 'node_modules/.cache/styles-inlined.css';

// matches the Style Settings plugin's config comment
const STYLE_SETTINGS_REGEX = /\/\*\s*@settings[\s\S]*?\*\//;

// inline files into CSS, lower native nesting (#648), and validate it
const stylesPlugin = {
  name: 'styles',
  setup(build) {
    build.onEnd(async () => {
      try {
        fileInliner('src/Styles/styles.css', STYLES_INLINED);
        const inlined = fs.readFileSync(STYLES_INLINED, 'utf8');

        // esbuild strips all comments, but Style Settings reads its config from one, so set it aside
        const settingsBlock = inlined.match(STYLE_SETTINGS_REGEX)?.[0] ?? '';

        // targets without native nesting support force esbuild to flatten the & rules
        const lowered = await esbuild.transform(inlined.replace(STYLE_SETTINGS_REGEX, ''), {
          loader: 'css',
          target: ['chrome100', 'safari15'],
        });
        const output = settingsBlock + '\n\n' + lowered.code;

        const existing = fs.existsSync('styles.css') ? fs.readFileSync('styles.css', 'utf8') : null;
        if (existing !== output) {
          fs.writeFileSync('styles.css', output);
          console.log(`\x1b[32m[styles] ✓ generated styles.css\x1b[0m`);
        }
      } catch (error) {
        console.error("\x1b[31m[styles] Error:\x1b[0m", error);
        process.exit(1);
      }

      // use esbuild to report CSS syntax errors
      await esbuild.build({
        entryPoints: ['styles.css'],
        bundle: false,
        write: false,
      }).catch((error) => {
        console.error("\x1b[31m[styles] Error:\x1b[0m", error);
        process.exit(1);
      });
    });
  },
};

/* ****************************************************************************
 * EXECUTE BUILD
 * ************************************************************************** */

const context = await esbuild.context({
	banner: {
		js: ESBUILD_BANNER,
	},
	entryPoints: ["src/main.ts"],
	bundle: true,
	external: [
		"obsidian",
		"electron",
		"@codemirror/autocomplete",
		"@codemirror/collab",
		"@codemirror/commands",
		"@codemirror/language",
		"@codemirror/lint",
		"@codemirror/search",
		"@codemirror/state",
		"@codemirror/view",
		"@lezer/common",
		"@lezer/highlight",
		"@lezer/lr",
		...builtinModules],
	format: "cjs",
	charset: "utf8",
	target: "es2018",
	loader: {
		'.md': 'text',
	},
	logLevel: "info",
	metafile: isBuildAnalyzeMode,
	plugins: [
		docsPlugin,
		stylesPlugin,
		...(isBuildProdMode ? [] : [typecheckPlugin]),
		eslintPlugin,
		stylelintPlugin,
	],
	sourcemap: (isBuildProdMode || isBuildAnalyzeMode) ? false : "inline",
	treeShaking: true,
	minify: (isBuildProdMode || isBuildAnalyzeMode) ? true : false,
	outfile: "main.js",
});

if (isBuildProdMode) {
	await context.rebuild();
	process.exit(0);
} 
else if (isBuildAnalyzeMode) {
	let build = await context.rebuild();
	console.log(await analyzeMetafile(build.metafile));
	process.exit(0);
} 
else {
	await context.watch();

	// watch for changes to files outside the build process
	const watcher = chokidar.watch(['docs/wiki', 'src/Api', 'src/Cli/cli.json', 'src/Gallery/gallery.json', 'src/Gallery/gallery-items.json', 'src/Styles', 'build/docs.mjs', 'build/copy-skill-references.mjs']);
	watcher.on('ready', () => {
		console.log('[watch] watching for changes...');
	});
	watcher.on('change', async (path) => {
		console.log(`[watch] file modified: ${path}`);
		try {
			await context.rebuild();
		} 
		catch (error) {
			console.error('[watch] rebuild failed:', error);
		}
	});
}
